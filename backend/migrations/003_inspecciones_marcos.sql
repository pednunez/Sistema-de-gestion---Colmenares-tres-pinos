
-- ==========================================================
-- MIGRACIÓN 003 - INSPECCIONES Y DETALLE DE MARCOS
-- PROYECTO: COLMENARES TRES PINOS
-- ==========================================================
--
-- OBJETIVOS:
-- 1. Registrar presencia de alza.
-- 2. Registrar tiras de medicamento.
-- 3. Crear detalle individual de marcos.
-- 4. Conservar inspecciones históricas.
-- 5. Configurar permisos del rol de aplicación.
--
-- Ejecutar con un usuario propietario autorizado.
-- Requiere que existan las tablas originales.
-- ==========================================================

BEGIN;

-- ==========================================================
-- 1. AMPLIAR TABLA INSPECCIONES
-- ==========================================================

ALTER TABLE public.inspecciones
ADD COLUMN IF NOT EXISTS tiene_alza BOOLEAN;

ALTER TABLE public.inspecciones
ADD COLUMN IF NOT EXISTS tiras_medicamento INTEGER;

-- ==========================================================
-- 2. VALIDAR TIRAS DE MEDICAMENTO
-- ==========================================================

DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1
        FROM pg_constraint
        WHERE conname = 'ck_inspecciones_tiras_medicamento'
          AND conrelid = 'public.inspecciones'::regclass
    ) THEN

        ALTER TABLE public.inspecciones
        ADD CONSTRAINT ck_inspecciones_tiras_medicamento
        CHECK (
            tiras_medicamento IS NULL
            OR tiras_medicamento BETWEEN 1 AND 3
        );

    END IF;
END $$;

-- ==========================================================
-- 3. CREAR TABLA DE MARCOS
-- ==========================================================

CREATE TABLE IF NOT EXISTS public.inspeccion_marcos (

    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    inspeccion_id BIGINT NOT NULL,

    ubicacion VARCHAR(20) NOT NULL,

    numero INTEGER NOT NULL,

    contenido VARCHAR(30) NOT NULL,

    transferido_a_colmena_id BIGINT NULL,

    CONSTRAINT fk_inspeccion_marcos_inspeccion
        FOREIGN KEY (inspeccion_id)
        REFERENCES public.inspecciones(id),

    CONSTRAINT fk_inspeccion_marcos_destino
        FOREIGN KEY (transferido_a_colmena_id)
        REFERENCES public.colmenas(id),

    CONSTRAINT uq_inspeccion_marco_posicion
        UNIQUE (inspeccion_id, ubicacion, numero),

    CONSTRAINT ck_inspeccion_marco_numero
        CHECK (numero BETWEEN 1 AND 10),

    CONSTRAINT ck_inspeccion_marco_ubicacion
        CHECK (
            ubicacion IN ('CAMARA_CRIA', 'ALZA')
        ),

    CONSTRAINT ck_inspeccion_marco_contenido
        CHECK (
            contenido IN (
                'MIEL_Y_CRIA',
                'SOLO_CRIA',
                'SOLO_MIEL',
                'CERA_ESTIRADA',
                'CERA_ESTAMPADA',
                'CERA_UNTADA',
                'SIN_MARCO'
            )
        )
);

-- ==========================================================
-- 4. ÍNDICE PARA CONSULTAR MARCOS POR INSPECCIÓN
-- ==========================================================

CREATE INDEX IF NOT EXISTS ix_inspeccion_marcos_inspeccion_id
ON public.inspeccion_marcos (inspeccion_id);

-- ==========================================================
-- 5. PERMISOS DE LA APLICACIÓN
-- ==========================================================
--
-- La migración 002 define un rol restringido.
-- Solo otorgamos acceso si ya existe.
-- ==========================================================

DO $$
BEGIN

    IF EXISTS (
        SELECT 1
        FROM pg_roles
        WHERE rolname = 'colmenares_app'
    ) THEN

        GRANT SELECT, INSERT, UPDATE
        ON TABLE public.inspeccion_marcos
        TO colmenares_app;

        GRANT USAGE
        ON SEQUENCE public.inspeccion_marcos_id_seq
        TO colmenares_app;

    END IF;

END $$;

COMMIT;
